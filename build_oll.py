"""Generates oll_table.py: one shortest algorithm per OLL case (57 cases).

Search is bidirectional over F2L pieces + 'all yellow stickers', using only
R/U/F-type turns, so results look like real hand-friendly OLL algorithms.
Run:  python build_oll.py
"""
import time

from ll_common import LL_SLOTS, all_oll_states, f2l_pieces, oll_key, simplify, top_color
from cube import SLOTS
from f2l import _BiSearch, _MOVE_LIST, _current_slot

def tracked(cube):
    f = tuple(_current_slot(cube, c, r) for c, r in f2l_pieces(cube))
    y = top_color(cube)
    ys = tuple(sorted(i for i in range(54)
                      if cube.state[i] == y and SLOTS[i] != ((0, 1, 0), (0, 1, 0))))
    return f + ys


def bits(key):
    return "".join("1" if b else "0" for b in key)


def orbit_reps(states):
    seen, reps = set(), []
    for c in states[1:]:
        if oll_key(c) in seen:
            continue
        cc = c.copy()
        for _ in range(4):
            seen.add(oll_key(cc))
            cc.apply("U")
        reps.append(c)
    return reps


def _search(cube, goal, faces, cap):
    moves = [m for m in _MOVE_LIST if m[0][0] in faces]
    s = _BiSearch(tracked(cube), goal, moves, sort_tail=8)
    while s.solution is None and s.depth < cap:
        s.step()
    return simplify(s.solution) if s.solution is not None else None


def find_alg(cube, goal):
    """Prefer plain R/U/F algs; only add L (and then B) when that is shorter."""
    best, faces = _search(cube, goal, "RUF", 14), "RUF"
    for extra, cap in (("RUFL", 12), ("RUFLB", 11)):
        if best is None or len(best) >= 12:
            limit = min(cap, len(best) - 1) if best else cap
            alt = _search(cube, goal, extra, limit)
            if alt is not None and (best is None or len(alt) < len(best)):
                best, faces = alt, extra
    if best is None:
        raise RuntimeError("no alg found")
    return best, faces


if __name__ == "__main__":
    states = all_oll_states()
    goal = tracked(states[0])
    reps = orbit_reps(states)
    table, t0 = {}, time.time()
    for i, c in enumerate(reps, 1):
        alg, faces = find_alg(c, goal)
        table[bits(oll_key(c))] = " ".join(alg)
        print(f"{i:2d}/57 {len(alg):2d} moves [{faces}] {' '.join(alg)}  ({time.time()-t0:.0f}s)", flush=True)
    with open("oll_table.py", "w") as f:
        f.write('"""OLL algorithms, generated by build_oll.py (57 cases). Do not edit.\n\n'
                'Key: 20 bits, which last-layer stickers are the top colour.\n'
                'Value: algorithm that orients the whole last layer (F2L untouched)."""\n\n')
        f.write("OLL_ALGS = {\n")
        for k, v in table.items():
            f.write(f'    "{k}": "{v}",\n')
        f.write("}\n")
